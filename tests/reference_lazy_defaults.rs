//! Complete pre-BinaryTreeLazy2 Lazy-family frames and exact owner operations.
//! Captured by the reviewed clock-free benchmark before the BinaryTreeLazy2 changes with recorded
//! overlays; see fixtures/reference-lazy-baseline/provenance.json.
#![forbid(unsafe_code)]

use zstdoxide::{CompressionParameterRequest, FrameHeader, ReferenceStrategy, SourceSize};
use zstdoxide_test_allocator::{AllocatorConfig, TrackingAllocator};

const PACK: &[u8] = include_bytes!("fixtures/reference-lazy-baseline/frames.bin");
const ROWS: &str = include_str!("fixtures/reference-lazy-baseline/expected.tsv");
const SEED: u64 = 0x5eed_fa57_2026_1009;
const BLOCK: usize = 131_072;

struct Expected<'a> {
    workload: &'a str,
    profile: &'a str,
    source_len: usize,
    source_hash: u64,
    parameters: [u32; 7],
    offset: usize,
    length: usize,
    frame_hash: u64,
    allocation: [u128; 12],
}

fn rows() -> Vec<Expected<'static>> {
    ROWS.lines()
        .skip(1)
        .map(|line| {
            let f: Vec<_> = line.split('\t').collect();
            assert_eq!(f.len(), 28);
            Expected {
                workload: f[0],
                profile: f[1],
                source_len: f[2].parse().unwrap(),
                source_hash: u64::from_str_radix(f[3], 16).unwrap(),
                parameters: core::array::from_fn(|i| f[5 + i].parse().unwrap()),
                offset: f[12].parse().unwrap(),
                length: f[13].parse().unwrap(),
                frame_hash: u64::from_str_radix(f[14], 16).unwrap(),
                allocation: core::array::from_fn(|i| f[16 + i].parse().unwrap()),
            }
        })
        .collect()
}

fn fingerprint(bytes: &[u8]) -> u64 {
    bytes.iter().fold(0xcbf2_9ce4_8422_2325, |v, &b| {
        (v ^ u64::from(b)).wrapping_mul(0x100_0000_01b3)
    })
}

// Recipe copied from the frozen benchmark example, SHA256
// f4825d63a8b7bcadaf825951a48a3aa61fa52156c4214ce1885fd1587ff48c43.
// Expectations are archived observations, never generated by this recipe.
fn next(state: &mut u64) -> u8 {
    *state ^= *state << 13;
    *state ^= *state >> 7;
    *state ^= *state << 17;
    *state as u8
}
fn noise(mut state: u64, count: usize) -> Vec<u8> {
    (0..count).map(|_| next(&mut state)).collect()
}
fn skewed(count: usize) -> Vec<u8> {
    let mut result = Vec::with_capacity(count);
    let mut state = SEED;
    let phrase = b"Reference Fast one-shot benchmark with skewed literal frequencies.\n";
    for i in 0..count {
        let random = next(&mut state);
        result.push(if i >= 8192 && i % 509 != 0 {
            result[i - 8192]
        } else if i % 11 < 8 {
            phrase[i % phrase.len()]
        } else {
            random
        });
    }
    result
}
fn source(workload: &str) -> Vec<u8> {
    match workload {
        "far-history" => {
            let first = noise(SEED ^ 1, BLOCK);
            let gap = noise(SEED ^ 3, 11 * BLOCK);
            let text = skewed(BLOCK);
            [&first[..], &gap[..], &first[..], &text.repeat(4)].concat()
        }
        "skewed" => skewed(32768),
        "history" => {
            let a = noise(SEED ^ 1, BLOCK);
            let b = noise(SEED ^ 2, BLOCK);
            [&a[..], &b[..], &a[..]].concat()
        }
        "mixed" => {
            let a = skewed(BLOCK);
            let b = noise(SEED ^ 2, BLOCK);
            [&a[..], &b[..], &vec![b'z'; BLOCK], &a[..]].concat()
        }
        _ => panic!("unknown frozen workload"),
    }
}
fn request(profile: &str) -> CompressionParameterRequest {
    for (prefix, strategy) in [
        ("lazy1-", ReferenceStrategy::Lazy),
        ("lazy2-", ReferenceStrategy::Lazy2),
    ] {
        if let Some(base) = profile.strip_prefix(prefix) {
            let mut value = request(base);
            value.set_strategy(Some(strategy));
            return value;
        }
    }
    match profile {
        "level-1" => CompressionParameterRequest::with_level(1),
        "level-3" => CompressionParameterRequest::with_level(3),
        "chain-4" | "chain-8" | "row-16" | "row-32" | "row-64" | "row-capped" => {
            let (window, hash, chain, search, target) = match profile {
                "chain-4" => (14, 15, 14, 4, 0),
                "chain-8" => (14, 15, 14, 8, 0),
                "row-16" => (21, 12, 6, 1, 0),
                "row-32" => (21, 12, 6, 5, 0),
                "row-64" => (21, 19, 6, 6, 0),
                "row-capped" => (21, 19, 30, 30, 131_072),
                _ => unreachable!(),
            };
            let mut value = CompressionParameterRequest::with_level(3);
            value.set_strategy(Some(ReferenceStrategy::Greedy));
            value.set_window_log(window).unwrap();
            value.set_hash_log(hash).unwrap();
            value.set_chain_log(chain).unwrap();
            value.set_search_log(search).unwrap();
            value.set_min_match(4).unwrap();
            value.set_target_length(target).unwrap();
            value
        }
        _ => unreachable!(),
    }
}
fn frame(row: &Expected<'_>) -> &'static [u8] {
    assert!(row.length > 0);
    let end = row.offset.checked_add(row.length).unwrap();
    let bytes = PACK.get(row.offset..end).unwrap();
    assert_eq!(fingerprint(bytes), row.frame_hash);
    let (header, mut cursor) = FrameHeader::parse(bytes).unwrap();
    assert_eq!(header.content_size, Some(row.source_len as u64));
    assert_eq!(header.dictionary_id, 0);
    assert!(!header.has_checksum);
    // Check that the final standard block exhausts this extent exactly.
    loop {
        let h = bytes.get(cursor..cursor.checked_add(3).unwrap()).unwrap();
        let word = u32::from_le_bytes([h[0], h[1], h[2], 0]);
        let kind = (word >> 1) & 3;
        assert_ne!(kind, 3);
        let length = if kind == 1 { 1 } else { (word >> 3) as usize };
        cursor = cursor.checked_add(3).unwrap().checked_add(length).unwrap();
        assert!(cursor <= bytes.len());
        if word & 1 != 0 {
            break;
        }
    }
    assert_eq!(cursor, bytes.len());
    bytes
}
fn replay(profile: &str) {
    let selected: Vec<_> = rows()
        .into_iter()
        .filter(|r| r.profile == profile)
        .collect();
    assert_eq!(selected.len(), 4);
    for row in selected {
        let source = source(row.workload);
        assert_eq!(source.len(), row.source_len);
        assert_eq!(fingerprint(&source), row.source_hash);
        let request = request(profile);
        let saved = request;
        let raw = request
            .resolve(SourceSize::Known(source.len() as u64), 0)
            .unwrap()
            .to_raw();
        assert_eq!(
            [
                raw.window_log,
                raw.chain_log,
                raw.hash_log,
                raw.search_log,
                raw.min_match,
                raw.target_length,
                raw.strategy
            ],
            row.parameters
        );
        let expected = frame(&row);
        assert_eq!(
            zstdoxide::compress_with_parameters(&source, &request).unwrap(),
            expected
        );
        assert_eq!(
            zstdoxide::decompress(expected, source.len()).unwrap(),
            source
        );
        let owner = TrackingAllocator::new(AllocatorConfig {
            max_live_allocations: 512,
            fail_at: None,
        })
        .unwrap();
        let monitor = owner.monitor();
        let encoded = zstdoxide::compress_with_parameters_in(&source, &request, owner).unwrap();
        assert_eq!(encoded, expected);
        let resident = monitor.snapshot();
        assert!(!resident.violations.any());
        assert_eq!(resident.failures, 0);
        assert_eq!(resident.live_blocks, 1);
        assert_eq!(resident.zero_size_requests, 0);
        assert_eq!(resident.allocate_zeroed_calls, 0);
        assert_eq!(resident.grow_zeroed_calls, 0);
        assert_eq!(resident.shrink_calls, 0);
        assert_eq!(
            resident.attempts,
            resident.allocate_calls + resident.grow_calls
        );
        drop(encoded);
        monitor.assert_released();
        let released = monitor.snapshot();
        assert_eq!(released.identities_created, released.owners_dropped);
        // Exact byte/layout observations are qualified to the original target
        // and pinned toolchain. Other targets still enforce complete bytes,
        // category/owner invariants and full final release above.
        if cfg!(all(
            target_arch = "aarch64",
            target_os = "macos",
            target_pointer_width = "64"
        )) {
            let observed = [
                u128::from(resident.attempts),
                u128::from(resident.allocate_calls),
                u128::from(resident.grow_calls),
                u128::from(resident.peak_live_blocks),
                resident.peak_requested_bytes,
                resident.peak_bytes,
                resident.live_requested_bytes,
                resident.live_bytes,
                u128::from(released.identities_created),
                u128::from(released.owners_dropped),
                u128::from(released.live_blocks),
                released.live_bytes,
            ];
            assert_eq!(observed, row.allocation, "{} {profile}", row.workload);
        }
        assert_eq!(request, saved);
        assert_eq!(fingerprint(&source), row.source_hash);
    }
}

#[test]
fn complete_catalog_has_eighty_rows_and_thirty_six_consecutive_distinct_extents() {
    let rows = rows();
    assert_eq!(rows.len(), 80);
    let mut extents = Vec::new();
    let mut cursor = 0;
    let mut names = Vec::new();
    for row in rows {
        assert!(!names.contains(&(row.workload, row.profile)));
        names.push((row.workload, row.profile));
        let source = source(row.workload);
        assert_eq!(source.len(), row.source_len);
        assert_eq!(fingerprint(&source), row.source_hash);
        frame(&row);
        if !extents.contains(&(row.offset, row.length)) {
            assert_eq!(row.offset, cursor);
            cursor = cursor.checked_add(row.length).unwrap();
            extents.push((row.offset, row.length));
        }
    }
    assert_eq!(extents.len(), 36);
    assert_eq!(cursor, PACK.len());
}
