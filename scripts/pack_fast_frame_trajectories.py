#!/usr/bin/env python3
"""Derive bounded Rust-readable normal Fast trajectories; never compile/run C."""
from pathlib import Path
import argparse
import hashlib
import json
import struct

import import_fast_frame_publication as importer

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / 'tests/fixtures/reference-fast-frames'
READER = ROOT / 'tests/support/fast_frame_oracle.rs'


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def pack(value):
    result = bytearray(b'ZFTRJ01\0' + struct.pack('<II', 23, 64))
    block_count = 0
    for case in value['cases']:
        body = bytearray()
        row = case['recipe']
        begin = next(r for r in case['records'] if r['type'] == 'begin')
        blocks = [r for r in case['records'] if r['type'] == 'block']
        name = row['id'].encode('ascii')
        body.extend(struct.pack('<H', len(name)) + name)
        body.extend(struct.pack('<BBBBIIQ', row['window'], row['hash'], row['min_match'], 0,
                                row['target'], row['source_size'], int(begin['source_fnv64'], 16)))
        body.extend(struct.pack('<I', len(row['schedule'])))
        for size in row['schedule']:
            body.extend(struct.pack('<I', size))
        body.extend(struct.pack('<I', len(blocks)))
        for block in blocks:
            record = bytearray()
            floor = block['window']['dict_limit'] - 2
            candidate = block['candidate']
            record.extend(struct.pack('<4IBBH', block['call'], block['source_start'],
                                      block['source_bytes'], floor, block['kind'], int(candidate['fresh']), 0))
            for repeats in (block['semantic_before'], block['semantic_after'],
                            block['before']['raw_repeats'], block['after']['raw_repeats']):
                record.extend(struct.pack('<3I', *repeats))
            changes = block['hash']['changed']
            record.extend(struct.pack('<I', len(changes)))
            for change in changes:
                record.extend(struct.pack('<3I', *change))
            record.extend(struct.pack('<2Q', int(block['hash']['before_fnv64'], 16),
                                      int(block['hash']['after_fnv64'], 16)))
            if candidate['fresh']:
                record.extend(struct.pack('<3I', *block['candidate_state']['raw_repeats']))
                record.extend(struct.pack('<3I', *candidate['semantic_repeats']))
                literals = bytes.fromhex(candidate['literal_bytes'])
                record.extend(struct.pack('<II', candidate['trailing'], len(literals)))
                record.extend(literals)
                record.extend(struct.pack('<I', len(candidate['sequences'])))
                for ll, ml, offset, distance in candidate['sequences']:
                    record.extend(struct.pack('<4I', ll, ml, distance, offset))
            body.extend(struct.pack('<I', len(record)) + record)
            block_count += 1
        result.extend(struct.pack('<I', len(body)) + body)
    importer.inspect.need(block_count == 64 and len(result) <= 8 << 20, 'bounded exact trajectory pack')
    return bytes(result)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument('--check', action='store_true')
    action.add_argument('--write', action='store_true')
    args = parser.parse_args()
    # This is the strictly offline branch: no live module or subprocess is used.
    _, value, _ = importer.check(importer.COLLECTION)
    data = pack(value)
    metadata = {
        'schema_version': 1, 'binary_format': 'ZFTRJ01: bounded little-endian ordinary Fast trajectories',
        'upstream_revision': importer.inspect.REVISION, 'cases': 23, 'nonempty_blocks': 64,
        'excluded_partial_headers': 11, 'source_bytes': 1222674,
        'generator': 'scripts/pack_fast_frame_trajectories.py', 'generator_sha256': digest(Path(__file__)),
        'reader': 'tests/support/fast_frame_oracle.rs', 'reader_sha256': digest(READER),
        'input_sha256': {
            str(path.relative_to(ROOT)): digest(path) for path in (
                importer.COLLECTION / 'manifest.json', importer.COLLECTION / 'observations.json.gz',
                importer.COLLECTION / 'frames.bin', importer.COLLECTION / 'frame_oracle.c',
                ROOT / 'scripts/import_fast_frame_publication.py',
                ROOT / 'scripts/oracles/fast_frame_publication_support.py')},
        'fixture': {'path': 'cases.bin', 'size': len(data), 'sha256': hashlib.sha256(data).hexdigest()},
        'policy': 'Derived from frozen ordinary C observations, without new C execution. Raw C third repeat cells are distinct from full wire triples. Source bytes are regenerated by the Rust reader; no compressed-frame decoder is supplied here.',
    }
    encoded = (json.dumps(metadata, sort_keys=True, indent=2) + '\n').encode()
    if args.write:
        DESTINATION.mkdir(parents=True, exist_ok=True)
        (DESTINATION / 'cases.bin').write_bytes(data)
        (DESTINATION / 'provenance.json').write_bytes(encoded)
    else:
        importer.inspect.need((DESTINATION / 'cases.bin').read_bytes() == data, 'frozen packed trajectories')
        importer.inspect.need((DESTINATION / 'provenance.json').read_bytes() == encoded, 'trajectory provenance')
    print(f'{"Wrote" if args.write else "Verified"} 23 ordinary Fast trajectories / 64 blocks ({len(data)} bytes); no C execution.')


if __name__ == '__main__':
    main()
