#!/usr/bin/env python3
"""Generate a reproducible zstd v1.5.7 decodecorpus replay suite.

Reference source must be an external checkout. The official executables are
used only to create and independently verify fixture data.
"""

import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile

REVISION = "f8745da6ff1ad1e7bab384bd1f9d742439278e99"
ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / "tests" / "upstream" / "decodecorpus"
MODES = [
    ("mixed", 101, 17, 16, []),
    ("known-size", 202, 17, 16, ["--content-size"]),
    ("raw", 303, 17, 16, ["--block-type=0"]),
    ("rle", 404, 17, 16, ["--block-type=1", "--content-size"]),
    ("compressed", 505, 17, 16, ["--block-type=2"]),
    ("small-blocks", 606, 10, 16, []),
    ("small-content", 707, 10, 10, []),
    ("large-content", 808, 17, 18, ["--content-size"]),
]
COUNT = 12


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def inspect_frame(encoded, header_only=False):
    """Read wire metadata independently of either decoder for coverage checks."""
    if encoded[:4] != bytes.fromhex("28b52ffd"):
        raise ValueError("missing standard frame magic")
    descriptor = encoded[4]
    single_segment = bool(descriptor & 32)
    cursor = 5
    window = 0
    if not single_segment:
        window_descriptor = encoded[cursor]
        cursor += 1
        window_base = 1 << (10 + (window_descriptor >> 3))
        window = window_base + (window_base >> 3) * (window_descriptor & 7)
    dictionary_bytes = [0, 1, 2, 4][descriptor & 3]
    dictionary_id = int.from_bytes(encoded[cursor:cursor + dictionary_bytes], "little")
    cursor += dictionary_bytes
    size_bytes = [int(single_segment), 2, 4, 8][descriptor >> 6]
    content_size = None
    if size_bytes:
        content_size = int.from_bytes(encoded[cursor:cursor + size_bytes], "little")
        if size_bytes == 2:
            content_size += 256
    cursor += size_bytes
    if single_segment:
        window = content_size
    result = {
        "header_size": cursor,
        "window_size": window,
        "content_size": content_size,
        "dictionary_id": dictionary_id,
        "checksum": bool(descriptor & 4),
        "single_segment": single_segment,
    }
    if header_only:
        if len(encoded) != cursor:
            raise ValueError("header-only fixture contains payload")
        return result
    blocks = []
    while True:
        block_header = int.from_bytes(encoded[cursor:cursor + 3], "little")
        if cursor + 3 > len(encoded):
            raise ValueError("truncated block header")
        cursor += 3
        kind = (block_header >> 1) & 3
        size = block_header >> 3
        blocks.append({"kind": kind, "size": size})
        cursor += 1 if kind == 1 else size
        if block_header & 1:
            break
    if result["checksum"]:
        cursor += 4
    if cursor != len(encoded):
        raise ValueError("block walk did not consume complete frame")
    result["blocks"] = blocks
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("upstream", type=Path, help="external pinned zstd git checkout")
    parser.add_argument("--decodecorpus", help="official generator; defaults to UPSTREAM/tests/decodecorpus")
    parser.add_argument("--zstd", default=os.environ.get("ZSTD_BIN", "zstd"))
    parser.add_argument("--check", action="store_true", help="verify all generated bytes without writing")
    args = parser.parse_args()
    revision = subprocess.check_output(
        ["git", "-C", str(args.upstream), "rev-parse", "HEAD"], text=True
    ).strip()
    if revision != REVISION:
        parser.error(f"expected source revision {REVISION}; found {revision}")
    subprocess.run(
        ["git", "-C", str(args.upstream), "diff", "--quiet", "HEAD", "--", "tests/decodecorpus.c", "lib"],
        check=True,
    )
    version = subprocess.check_output([args.zstd, "--version"], text=True)
    if "v1.5.7" not in version:
        parser.error(f"expected zstd v1.5.7; found {version.strip()}")
    generator = args.decodecorpus or str(args.upstream / "tests" / "decodecorpus")
    outputs = {}
    source = (args.upstream / "tests" / "decodecorpus.c").read_bytes()
    manifest = {
        "upstream_revision": REVISION,
        "generator_source": "tests/decodecorpus.c",
        "generator_source_sha256": sha256(source),
        "frames_per_mode": COUNT,
        "modes": [],
        "frames": [],
        "headers": [],
    }
    rust_frames = ["// Generated by scripts/generate_upstream_decodecorpus.py; do not edit.", "const FRAMES: &[FrameFixture] = &["]
    rust_headers = ["const HEADERS: &[HeaderFixture] = &["]
    with tempfile.TemporaryDirectory(prefix="zstdoxide-decodecorpus-") as temporary:
        temp = Path(temporary)
        for name, seed, block_log, content_log, extra in MODES:
            encoded_dir = temp / name / "encoded"
            original_dir = temp / name / "original"
            encoded_dir.mkdir(parents=True)
            original_dir.mkdir()
            arguments = [f"-s{seed}", f"-n{COUNT}", f"--max-block-size-log={block_log}", f"--max-content-size-log={content_log}", *extra]
            subprocess.run(
                [generator, *arguments, f"-p{encoded_dir}", f"-o{original_dir}"],
                check=True, capture_output=True,
            )
            manifest["modes"].append({"name": name, "arguments": arguments})
            for index in range(COUNT):
                encoded = (encoded_dir / f"z{index:06}.zst").read_bytes()
                original = (original_dir / f"z{index:06}").read_bytes()
                oracle = subprocess.check_output([args.zstd, "-q", "-d", "-c"], input=encoded)
                if oracle != original:
                    raise RuntimeError(f"independent oracle mismatch: {name}-{index:02}")
                basename = f"{name}-{index:02}"
                outputs[f"{basename}.zst"] = encoded
                outputs[f"{basename}.raw"] = original
                metadata = inspect_frame(encoded)
                if len(original) > 1 << content_log:
                    raise RuntimeError(f"content cap violated: {basename}")
                if any(block["size"] > 1 << block_log for block in metadata["blocks"]):
                    raise RuntimeError(f"block cap violated: {basename}")
                manifest["frames"].append({
                    "name": basename, "encoded_size": len(encoded), "encoded_sha256": sha256(encoded),
                    "original_size": len(original), "original_sha256": sha256(original), **metadata,
                })
                size = "None" if metadata["content_size"] is None else f"Some({metadata['content_size']})"
                rust_frames.append(
                    "    FrameFixture { "
                    f'name: "{basename}", encoded: include_bytes!("{basename}.zst"), original: include_bytes!("{basename}.raw"), '
                    f"window_size: {metadata['window_size']}, content_size: {size}, checksum: {str(metadata['checksum']).lower()}, "
                    f"max_block_size: {1 << block_log}, max_content_size: {1 << content_log} " + "},"
                )
        for seed in range(1, 17):
            arguments = [f"-s{seed}", "--frame-header-only", "--max-content-size-log=16"]
            path = temp / "header.zst"
            subprocess.run([generator, *arguments, f"-p{path}"], check=True, capture_output=True)
            encoded = path.read_bytes()
            metadata = inspect_frame(encoded, header_only=True)
            name = f"header-{seed:02}"
            outputs[f"{name}.zst"] = encoded
            manifest["headers"].append({"name": name, "arguments": arguments, "sha256": sha256(encoded), **metadata})
            size = "None" if metadata["content_size"] is None else f"Some({metadata['content_size']})"
            rust_headers.append(
                "    HeaderFixture { "
                f'name: "{name}", encoded: include_bytes!("{name}.zst"), window_size: {metadata["window_size"]}, '
                f"content_size: {size}, checksum: {str(metadata['checksum']).lower()} " + "},"
            )
    kinds = {block["kind"] for frame in manifest["frames"] for block in frame["blocks"]}
    if kinds != {0, 1, 2}:
        raise RuntimeError(f"missing block-kind coverage: {kinds}")
    if {frame["content_size"] is None for frame in manifest["frames"]} != {True, False}:
        raise RuntimeError("missing known/unknown content size coverage")
    rust_frames.append("];")
    rust_headers.append("];")
    outputs["cases.rs"] = ("\n".join(rust_frames + rust_headers) + "\n").encode()
    outputs["manifest.json"] = (json.dumps(manifest, indent=2) + "\n").encode()
    for relative, data in outputs.items():
        path = DESTINATION / relative
        if args.check:
            if path.read_bytes() != data:
                raise RuntimeError(f"reproducibility mismatch: {relative}")
        else:
            path.write_bytes(data)
    verb = "Verified" if args.check else "Generated"
    print(f"{verb} {len(manifest['frames'])} complete frames and {len(manifest['headers'])} headers")
    print(f"Total stored bytes: {sum(map(len, outputs.values())):,}")


if __name__ == "__main__":
    main()
